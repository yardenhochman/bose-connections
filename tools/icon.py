#!/usr/bin/env python3
"""Generate the app mark: outside-sound ridges on slate mist.

One geometry, several outputs: Android adaptive icon layers (vector), the web
favicon (SVG) and the macOS app icon source (SVG; PNG when rsvg-convert exists).
Run from anywhere: python3 tools/icon.py
"""
import math,os,shutil,subprocess,sys
from pathlib import Path
PEAKS=[  # per ridge: list of (center u, width, amp)
 [(0.42,0.10,0.55),(0.60,0.08,0.4)],
 [(0.50,0.09,0.75),(0.36,0.07,0.3)],
 [(0.40,0.08,0.5),(0.56,0.09,1.0)],
 [(0.46,0.10,0.7),(0.64,0.07,0.35)],
 [(0.38,0.08,0.35),(0.52,0.10,0.55)],
]
def prof(i,u):
    v=sum(a*math.exp(-((u-c)/w)**2) for c,w,a in PEAKS[i])
    return v*math.exp(-((u-0.5)/0.24)**2)
def ridge(i,base,rise,x0=-2,x1=110,n=40):
    pts=[]
    for s in range(n+1):
        u=s/n;x=x0+(x1-x0)*u
        pts.append((x,base-rise*prof(i,u)))
    # Catmull-Rom -> cubic beziers
    d=f"M{pts[0][0]:.2f},{pts[0][1]:.2f}"
    for k in range(len(pts)-1):
        p0=pts[max(k-1,0)];p1=pts[k];p2=pts[k+1];p3=pts[min(k+2,len(pts)-1)]
        c1=(p1[0]+(p2[0]-p0[0])/6,p1[1]+(p2[1]-p0[1])/6);c2=(p2[0]-(p3[0]-p1[0])/6,p2[1]-(p3[1]-p1[1])/6)
        d+=f"C{c1[0]:.2f},{c1[1]:.2f} {c2[0]:.2f},{c2[1]:.2f} {p2[0]:.2f},{p2[1]:.2f}"
    return d
BASES=[47,55,63,71,79];RISE=24
TOP,BOT='#33424b','#121a1f'   # slate mist
INK='#e3e8ea';OCHRE='#d6a858'
ALPHA=[0.30,0.45,0.62,0.82,1.0]
def layers(mono=False,rise=RISE):
    out=[]
    for i,b in enumerate(BASES):
        d=ridge(i,b,rise if not mono else 9)
        out.append((d,d+"L110,110L-2,110Z",i))
    return out
def svg(mask=None,size=108,mono=False):
    g=f'<linearGradient id="g" x1="0" y1="0" x2="0" y2="108" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{TOP}"/><stop offset="1" stop-color="{BOT}"/></linearGradient>'
    body=f'<rect width="108" height="108" fill="url(#g)"/>'
    # faint mist glow
    body+=f'<radialGradient id="m" cx="54" cy="40" r="44" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#9fb0b8" stop-opacity="0.22"/><stop offset="1" stop-color="#9fb0b8" stop-opacity="0"/></radialGradient><rect width="108" height="108" fill="url(#m)"/>'
    for d,fill,i in layers():
        body+=f'<path d="{fill}" fill="url(#g)"/>'
        col=OCHRE if i==len(BASES)-1 else INK
        body+=f'<linearGradient id="s{i}" x1="0" y1="0" x2="108" y2="0" gradientUnits="userSpaceOnUse"><stop offset="0.08" stop-color="{col}" stop-opacity="0"/><stop offset="0.3" stop-color="{col}" stop-opacity="{ALPHA[i]}"/><stop offset="0.7" stop-color="{col}" stop-opacity="{ALPHA[i]}"/><stop offset="0.92" stop-color="{col}" stop-opacity="0"/></linearGradient>'
        body+=f'<path d="{d}" fill="none" stroke="url(#s{i})" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round"/>'
    clip=''
    if mask=='circle':clip='<clipPath id="c"><circle cx="54" cy="54" r="54"/></clipPath>'
    elif mask=='squircle':clip='<clipPath id="c"><path d="M54,0C92,0 108,16 108,54C108,92 92,108 54,108C16,108 0,92 0,54C0,16 16,0 54,0Z"/></clipPath>'
    inner=f'<g clip-path="url(#c)">{body}</g>' if clip else body
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108"><defs>{g}{clip}</defs>{inner}</svg>'

def hexa(col,a):return '#%02X%s'%(round(a*255),col[1:].upper())
def vgrad_h(col,a):
    return f'''<aapt:attr name="android:strokeColor"><gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="0">
<item android:offset="0.08" android:color="{hexa(col,0)}"/><item android:offset="0.3" android:color="{hexa(col,a)}"/><item android:offset="0.7" android:color="{hexa(col,a)}"/><item android:offset="0.92" android:color="{hexa(col,0)}"/></gradient></aapt:attr>'''
def vgrad_bg(attr):
    return f'''<aapt:attr name="android:{attr}"><gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="108"><item android:offset="0" android:color="{TOP}"/><item android:offset="1" android:color="{BOT}"/></gradient></aapt:attr>'''
HEAD='<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icon.py: outside-sound ridges on slate mist. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
def xml_background():
    return HEAD+f'<path android:pathData="M0,0h108v108h-108z">{vgrad_bg("fillColor")}</path>\n<path android:pathData="M0,0h108v108h-108z"><aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="54" android:centerY="40" android:gradientRadius="44"><item android:offset="0" android:color="#389FB0B8"/><item android:offset="1" android:color="#009FB0B8"/></gradient></aapt:attr></path>\n</vector>\n'
def xml_foreground(mono=False):
    out=HEAD
    for d,fill,i in layers(mono=mono):
        if not mono: out+=f'<path android:pathData="{fill}">{vgrad_bg("fillColor")}</path>\n'
        col='#FFFFFF' if mono else (OCHRE if i==len(BASES)-1 else INK)
        out+=f'<path android:pathData="{d}" android:strokeWidth="{2.6 if not mono else 3}" android:strokeLineCap="round" android:strokeLineJoin="round">{vgrad_h(col,1 if mono else ALPHA[i])}</path>\n'
    return out+'</vector>\n'

def mac_svg():
    # macOS: rounded square inset on a 1024 canvas, per the system icon grid.
    inner=svg(None).split('viewBox="0 0 108 108">',1)[1].rsplit('</svg>',1)[0]
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
            '<defs><clipPath id="r"><rect x="100" y="100" width="824" height="824" rx="185"/></clipPath></defs>'
            f'<g clip-path="url(#r)"><g transform="translate(100,100) scale({824/108})"><svg viewBox="0 0 108 108" width="108" height="108">{inner}</svg></g></g></svg>')

ADAPTIVE='''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
'''

def main():
    root=Path(__file__).resolve().parent.parent
    draw=root/'android/res/drawable';mip=root/'android/res/mipmap-anydpi-v26'
    draw.mkdir(parents=True,exist_ok=True);mip.mkdir(parents=True,exist_ok=True)
    (draw/'ic_launcher_background.xml').write_text(xml_background())
    (draw/'ic_launcher_foreground.xml').write_text(xml_foreground())
    (draw/'ic_launcher_monochrome.xml').write_text(xml_foreground(True))
    for name in ('ic_launcher.xml','ic_launcher_round.xml'):(mip/name).write_text(ADAPTIVE)
    (root/'web/favicon.svg').write_text(svg('squircle',size=64))
    (root/'mac/AppIcon.svg').write_text(mac_svg())
    if shutil.which('rsvg-convert'):
        subprocess.run(['rsvg-convert','-w','1024','-h','1024',str(root/'mac/AppIcon.svg'),'-o',str(root/'mac/AppIcon.png')],check=True)
    print('Wrote Android icon layers, web/favicon.svg and mac/AppIcon.svg/.png')

if __name__=='__main__':main()
